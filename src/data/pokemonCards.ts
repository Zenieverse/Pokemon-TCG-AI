export function getCardById(id: string): Card {
  const card = CARD_DATABASE.find((c) => c.id === id);
  if (!card) {
    // Fallback dummy card
    return {
      id,
      name: 'Unknown Card',
      cardType: 'energy',
      energyType: 'Colorless',
    };
  }
  return { ...card };
}
